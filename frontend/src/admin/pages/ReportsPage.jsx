import { useEffect, useState } from 'react';
import { api } from '../../api/client';
import { Select } from '../../components/Select';

export function ReportsPage({ showToast }) {
  const [reports, setReports] = useState(null);
  const [statusFilter, setStatusFilter] = useState('all');

  async function load() {
    const query = statusFilter === 'all' ? '' : `?status=${statusFilter}`;
    const data = await api.get(`/admin/reports${query}`);
    setReports(data);
  }

  useEffect(() => {
    load();
  }, [statusFilter]);

  async function approve(r) {
    await api.post(`/admin/reports/${r.report_id}/approve`);
    showToast(`${r.report_type} report approved`);
    load();
  }

  return (
    <>
      <div style={{ display: 'flex', alignItems: 'center', gap: 12, marginBottom: 16 }}>
        <Select
          style={{ maxWidth: 180 }}
          value={statusFilter}
          onChange={(v) => setStatusFilter(v)}
          options={[
            { value: 'all', label: 'All statuses' },
            { value: 'pending', label: 'Pending' },
            { value: 'approved', label: 'Approved' },
          ]}
        />
      </div>

      <div className="card elev-sm" style={{ padding: 0, overflow: 'hidden' }}>
        <div className="table-wrap">
          <table className="table">
            <thead>
              <tr>
                <th>Type</th>
                <th>Details</th>
                <th>Generated by</th>
                <th>Generated</th>
                <th>Status</th>
                <th style={{ width: 110 }}>Actions</th>
              </tr>
            </thead>
            <tbody>
              {reports?.map((r) => (
                <tr key={r.report_id}>
                  <td style={{ fontWeight: 600, textTransform: 'capitalize' }}>{r.display_type || r.report_type}</td>
                  <td style={{ opacity: 0.75, maxWidth: 320 }}>{r.details || '—'}</td>
                  <td style={{ opacity: 0.75 }}>{r.generated_by_name}</td>
                  <td style={{ opacity: 0.65 }}>{new Date(r.generated_date).toLocaleString()}</td>
                  <td>
                    <span className={r.status === 'approved' ? 'tag tag-success' : 'tag tag-warning'}>{r.status}</span>
                  </td>
                  <td>
                    {r.status === 'pending' && (
                      <button type="button" className="btn btn-secondary" onClick={() => approve(r)}>
                        Approve
                      </button>
                    )}
                  </td>
                </tr>
              ))}
              {reports && reports.length === 0 && (
                <tr>
                  <td colSpan={6} style={{ opacity: 0.6, textAlign: 'center', padding: 24 }}>
                    No reports found.
                  </td>
                </tr>
              )}
            </tbody>
          </table>
        </div>
      </div>
    </>
  );
}
